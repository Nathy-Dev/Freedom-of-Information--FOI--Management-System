export const users: User[] = seeds.map(({ createdDaysAgo, ...seed }) => ({
  ...seed,
  initials: initialsOf(seed.name.replace(/^(Barr\.|Dr\.|Engr\.)\s*/, '')),
  createdAt: relativeIso(-createdDaysAgo),
  updatedAt: relativeIso(-Math.min(createdDaysAgo, Math.round(createdDaysAgo / 3))),
}))

export const usersById = new Map(users.map((u) => [u.id, u]))

export function userName(id: string | null | undefined) {
  if (!id) return 'Unassigned'
  if (id === 'system') return 'System'
  return usersById.get(id)?.name ?? 'Unknown user'
}

